'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const source=fs.readFileSync('web/outbound-subscriptions.js','utf8');
const flags=fs.readFileSync('web/country-flags.js','utf8');
const css=fs.readFileSync('web/outbound-subscriptions.css','utf8');
const index=fs.readFileSync('web/index.html','utf8');
assert(index.includes('static/outbound-subscriptions.js?v=122'));
assert(index.includes('static/outbound-subscriptions.css?v=125'));
assert(!source.includes('🏳️ Добавить флаг'),'Windows does not consistently render white flag emoji');
assert(source.includes("icon.classList.add('outsub-add-flag-icon')"));
assert(source.includes("choose.append(icon,document.createTextNode('Добавить флаг'))"));
assert(source.includes("const term=country.flag"),'click must store the Unicode flag');
assert(!source.includes("const term=country.english"),'do not store country names on selection');
assert(source.includes("if(!lines.includes(term))area.value=existing"));
assert(source.includes("chip.title=country.ru+' ('+country.code+')'"));
assert(!source.includes("chip.appendChild(make('span','',country.ru))"),'chip must show flag only');
assert(source.includes('directory.createIcon(country.code)'),'SVG chip must render in older browsers');
assert(source.includes('MUICountryFlags?.aliases?.[item.code]'),'picker must recognize aliases such as США');
assert(source.includes("area.dispatchEvent(new Event('input',{bubbles:true}))"),'preview must repaint live');
assert(flags.includes('country.flag.toLocaleLowerCase'),'saved emoji must map back to country');
assert(css.includes('.outsub-filter-field .outsub-add-flag-icon'));
assert(css.includes('.outsub-dialog .outsub-country-chip .outsub-flag-svg'));
console.log('PASS: local SVG Add Flag icon, Unicode flag terms, aliases, duplicate protection, color flag chips');
