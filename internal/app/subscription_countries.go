var subscriptionCountryUpperCode = regexp.MustCompile(`(?:^|[^A-Za-z])([A-Z]{2})(?:$|[^A-Za-z])`)
var subscriptionCountryNamesSorted = func() []struct{ Code, Name string } {
	values := make([]struct{ Code, Name string }, 0, 500)
	for c, n := range subscriptionCountryNames {
		values = append(values, struct{ Code, Name string }{c, n})
	}
	for c, all := range subscriptionCountryAliases {
		for _, label := range strings.Split(all, "|") {
			values = append(values, struct{ Code, Name string }{c, label})
		}
	}
	sort.SliceStable(values, func(i, j int) bool { return len([]rune(values[i].Name)) > len([]rune(values[j].Name)) })
	return values
}()

func subscriptionCountryNormalize(raw string) string {
	return strings.Join(strings.FieldsFunc(strings.ToLower(raw), func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsNumber(r) }), " ")
}
func subscriptionCountryCode(name string) string {
	chars := []rune(name)
	for i := 0; i+1 < len(chars); i++ {
		a, b := chars[i], chars[i+1]
		if a >= 0x1F1E6 && a <= 0x1F1FF && b >= 0x1F1E6 && b <= 0x1F1FF {
			code := string([]rune{'A' + (a - 0x1F1E6), 'A' + (b - 0x1F1E6)})
			if _, ok := subscriptionCountryNames[code]; ok {
				return code
			}
		}
	}
	for _, match := range subscriptionCountryUpperCode.FindAllStringSubmatch(name, -1) {
		if _, ok := subscriptionCountryNames[match[1]]; ok {
			return match[1]
		}
	}
	normalized := " " + subscriptionCountryNormalize(name) + " "
	for _, item := range subscriptionCountryNamesSorted {
		term := subscriptionCountryNormalize(item.Name)
		if len([]rune(term)) >= 3 && strings.Contains(normalized, " "+term+" ") {
			return item.Code
		}
	}
	return ""
}
func subscriptionCountryFlag(code string) string {
	if len(code) != 2 {
		return ""
	}
	code = strings.ToUpper(code)
	if _, ok := subscriptionCountryNames[code]; !ok {
		return ""
	}
	return string([]rune{rune(0x1F1E6 + int(code[0]-'A')), rune(0x1F1E6 + int(code[1]-'A'))})
}
func subscriptionCountryFilterText(name string) string {
	code := subscriptionCountryCode(name)
	if code == "" {
		return strings.ToLower(name)
	}
	return strings.ToLower(name) + " " + strings.ToLower(subscriptionCountryFlag(code)) + " " + strings.ToLower(subscriptionCountryNames[code]) + " " + strings.ToLower(subscriptionCountryAliases[code]) + " " + strings.ToLower(code)
}
